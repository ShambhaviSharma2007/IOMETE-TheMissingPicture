function SectionDivider({ title }: { title: string }) {
  return (
    <div style={{ display: 'flex', alignItems: 'center', gap: '1rem', margin: '2rem 0 1rem' }}>
      <div style={{ height: 1, flex: 1, background: 'var(--border-subtle)' }} />
      <span style={{ fontSize: '0.6875rem', fontWeight: 600, letterSpacing: '0.12em', textTransform: 'uppercase', color: 'var(--text-muted)', flexShrink: 0 }}>{title}</span>
      <div style={{ height: 1, flex: 1, background: 'var(--border-subtle)' }} />
    </div>
  );
}

// ─── Copy to clipboard ────────────────────────────────────────────────────────

function generateMarkdown(state: ReturnType<typeof useSession>['state']): string {
  const date = state.reportGeneratedAt
    ? new Date(state.reportGeneratedAt).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })
    : new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });

  const selectedReqs = REQUIREMENTS.filter(r => state.selectedRequirements.includes(r.id));
  const recConf = state.recommendation ? RECOMMENDATION_CONFIG[state.recommendation] : null;

  const blockingQs = DIFFICULT_QUESTIONS
    .filter(q => state.questionDispositions[q.id] === 'blocking')
    .map(q => `- **${q.question}** — ${q.evidenceNote}`).join('\n');

  const needsAnswerQs = DIFFICULT_QUESTIONS
    .filter(q => state.questionDispositions[q.id] === 'needs_answer')
    .map(q => `- ${q.question}`).join('\n');

  return `# IOMETE Platform Evaluation — Aurelia Capital
**Prepared by:** Maya Sharma, Director of Data Platforms
**Date:** ${date}
**Status:** Internal draft — not for distribution

---

## Executive Summary
${state.userNote || 'No personal note added.'}

**Recommendation:** ${recConf ? recConf.label : 'Not yet generated'}

${recConf ? recConf.description : ''}

---

## Requirements Selected (${selectedReqs.length})
${selectedReqs.map(r => `- **${r.label}** — ${r.description}`).join('\n')}

---

## Capability Coverage
- ✅ Supported: ${state.coverageSummary.supported} capability mappings directly evidenced
- 🟡 Assumed: ${state.coverageSummary.assumed} capability mappings inferred from architecture
- ⬜ Unknown: ${state.coverageSummary.unknown} capability mappings require validation

---

## Blocking Questions
${blockingQs || 'None recorded.'}

## Questions Needing Vendor Answers
${needsAnswerQs || 'None recorded.'}

---

## Committee Assessment
${EXECUTIVES.map(e => {
  const stance = state.executiveStances[e.id];
  const note = state.executiveAnnotations[e.id];
  return `**${e.name} (${e.title}):** ${stance === 'unset' ? 'Not assessed' : stance}\n${note ? `Notes: ${note}` : ''}`;
}).join('\n\n')}

---

## Financial Assumptions (User-Entered Estimates)
> ⚠ All figures below are estimates entered by the user. IOMETE licence cost is unknown — vendor quote required.

${state.financialModel.infrastructure.map(f => `- ${f.label}: ${f.isUnknown ? 'TBD' : '£' + f.value.toLocaleString()}`).join('\n')}

---

*Generated by IOMETE Buyer Navigator. Evidence states (Supported / Assumed / Unknown) are applied throughout. No IOMETE capabilities, pricing, or customer references have been invented.*
`;
}

